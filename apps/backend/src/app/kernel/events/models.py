"""Таблицы механики событий: очередь исходящих и журнал обработанных.

Обе таблицы живут в ядре, а не в бизнес-модуле. Outbox — часть контракта
транзакции («побочный эффект коммитится вместе с данными»), а журнал
обработанных — часть контракта доставки («at-least-once, повтор безвреден»).
Модуль, который завёл бы свою копию любой из них, сломал бы гарантию для всех
остальных.
"""

from datetime import datetime
from typing import Any
from uuid import UUID

from sqlalchemy import Index, String, Text, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.kernel.db.base import Base
from app.kernel.db.mixins import UUIDPkMixin


class OutboxMessage(Base, UUIDPkMixin):
    """Событие, записанное в транзакции и ждущее публикации в брокер.

    Строка появляется тем же коммитом, что и изменения данных: либо в базе
    есть и заказ, и его событие, либо нет ни того, ни другого. Публикацией
    занимается отдельный релей, поэтому недоступность брокера не роняет
    запрос — она лишь задерживает доставку.

    `id` — это же `message_id` сообщения в брокере: потребитель кладёт его в
    `processed_messages` и по нему отсеивает повторную доставку.
    """

    __tablename__ = "outbox"

    #: Индекс релея. Его запрос — `WHERE published_at IS NULL ORDER BY
    #: occurred_at, id`, поэтому индекс частичный: опубликованные строки живут
    #: до уборки и составляют почти всю таблицу, а в индексе они не нужны.
    #: Колонки ровно те, по которым идёт сортировка; тащить в индекс payload
    #: ради index-only scan бессмысленно — `FOR UPDATE SKIP LOCKED` всё равно
    #: обязан дойти до строки в куче, чтобы её заблокировать.
    #: Условие задано текстом: в момент выполнения тела класса колонка ещё не
    #: превратилась в `Column` и сослаться на неё выражением нельзя.
    __table_args__ = (
        Index(
            "ix_outbox_unpublished",
            "occurred_at",
            "id",
            postgresql_where=text("published_at IS NULL"),
        ),
    )

    topic: Mapped[str] = mapped_column(String(255), index=True)

    #: Событие целиком, сериализованное в JSON-совместимые типы. JSONB, а не
    #: JSON: он хранится разобранным, поэтому по полезной нагрузке можно
    #: искать при разборе инцидентов, не парся текст в запросе.
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB)

    #: Транспортные метаданные (`request_id`, `actor_id`): то, что нужно для
    #: связывания логов, но не является частью доменного события.
    headers: Mapped[dict[str, Any]] = mapped_column(JSONB)

    #: Момент наступления события по часам приложения. Не `server_default=now()`:
    #: в Postgres `now()` возвращает время начала транзакции, и все события
    #: одного коммита получили бы одинаковую метку — релей, сортирующий по
    #: `occurred_at`, потерял бы их порядок. Значение проставляет `emit()`.
    occurred_at: Mapped[datetime]

    #: NULL — «ещё не опубликовано». Единственный признак, по которому релей
    #: выбирает работу, поэтому он же — условие частичного индекса выше.
    published_at: Mapped[datetime | None] = mapped_column(default=None)

    #: Счётчик неудачных публикаций: по нему релей считает отсрочку и решает,
    #: когда сдаться и отправить сообщение в DLQ.
    attempts: Mapped[int] = mapped_column(default=0)

    #: Текст последней ошибки публикации. `Text`, а не `String(n)`: сообщение
    #: драйвера бывает длинным, а обрезанное на середине — бесполезным.
    last_error: Mapped[str | None] = mapped_column(Text, default=None)


class ProcessedMessage(Base):
    """Отметка «это сообщение уже обработано».

    Доставка at-least-once: брокер вправе прислать одно и то же сообщение
    дважды. Потребитель вставляет сюда `message_id` в своей же транзакции, и
    первичный ключ превращает «обработать дважды» в конфликт вставки, который
    видно до выполнения побочных эффектов.
    """

    __tablename__ = "processed_messages"

    #: `id` исходного `OutboxMessage`. Ключ приходит извне, поэтому UUIDv7
    #: здесь не генерируется — иначе отметка не совпала бы с сообщением.
    message_id: Mapped[UUID] = mapped_column(primary_key=True)

    #: Время отметки. Здесь `now()` от сервера уместен, в отличие от
    #: `occurred_at`: значение нужно только уборке старых записей, и порядок
    #: внутри одной транзакции для него не имеет смысла.
    #: Индекс — под запрос той самой уборки (`WHERE processed_at < ...`): без
    #: него ночной DELETE читал бы таблицу, которая растёт со скоростью всего
    #: потока сообщений сервиса.
    processed_at: Mapped[datetime] = mapped_column(server_default=func.now(), index=True)
