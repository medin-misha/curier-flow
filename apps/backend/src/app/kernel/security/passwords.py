"""Хеширование и проверка паролей на argon2id.

argon2id, а не bcrypt: он выигрывал Password Hashing Competition, рекомендован
OWASP и RFC 9106, не режет пароль на 72 байта и настраивается по памяти —
единственный ресурс, который дорого масштабировать на GPU.

Соль здесь не появляется ни в одной сигнатуре: `argon2-cffi` генерирует её сам
из `secrets` и кладёт в строку хеша вместе с параметрами. Самодельная соль в
этом месте — классический способ ослабить схему, ничего не выиграв.

Пароли и хеши не логируются ни на одном пути: ни в тексте исключения, ни в
структурном поле. Поэтому здесь нет ни одного вызова логгера — в этом модуле
нечего записать в лог, что не было бы утечкой.
"""

from typing import Final

from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerificationError

#: Параметры хеширования процесса. Умолчания argon2-cffi соответствуют профилю
#: RFC 9106 «low-memory» (64 МиБ, 3 прохода) и стоят порядка десятков
#: миллисекунд на запрос — цена, за которую перебор становится бессмысленным.
#:
#: Объект без состояния: он хранит только параметры и потокобезопасен, поэтому
#: один экземпляр на процесс — не глобальное состояние, а константа. Функции
#: принимают его аргументом, чтобы сервис с другим профилем стойкости (или
#: тест, которому нужны дешёвые параметры) не переопределял модульную глобаль.
PASSWORD_HASHER: Final = PasswordHasher()


def hash_password(password: str, *, hasher: PasswordHasher = PASSWORD_HASHER) -> str:
    """Захешировать пароль.

    Принимает пароль в открытом виде и параметры хеширования, возвращает
    строку формата PHC (`$argon2id$v=19$m=...`), в которой уже лежат соль и
    параметры. Хранить рядом что-то ещё не нужно.
    """
    return hasher.hash(password)


def verify_password(
    password: str,
    hashed: str,
    *,
    hasher: PasswordHasher = PASSWORD_HASHER,
) -> bool:
    """Проверить пароль против хеша.

    Принимает пароль и хеш, возвращает `True`, если они сходятся.

    Исключения библиотеки наружу не выпускаются: и «пароль не тот», и «в базе
    вместо хеша мусор» для вызывающего означают одно — вход не состоялся.
    Разные ветки ответа здесь опасны: по ним отличают несуществующего
    пользователя от существующего.
    """
    try:
        return hasher.verify(hashed, password)
    except (VerificationError, InvalidHashError):
        return False


def password_needs_rehash(hashed: str, *, hasher: PasswordHasher = PASSWORD_HASHER) -> bool:
    """Сообщить, что хеш посчитан по устаревшим параметрам.

    Принимает хеш, возвращает `True`, если он слабее текущих параметров.

    Пароль в открытом виде есть только в момент успешного входа, и это
    единственная возможность пересчитать хеш. Поэтому вызывать проверку нужно
    сразу после `verify_password`: иначе поднятая стойкость применится только
    к новым учётным записям, а старые останутся на параметрах позапрошлого
    года навсегда.
    """
    return hasher.check_needs_rehash(hashed)
