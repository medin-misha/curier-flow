"""Контекст текущей операции: идентификатор запроса и действующее лицо.

Значения нужны логам, обработчикам ошибок и outbox — то есть коду, который
вызывается из любой точки стека. Протаскивать их параметрами через все
сигнатуры бессмысленно, поэтому используются contextvars: они не текут между
задачами asyncio и корректно копируются в дочерние таски.

Заполняет контекст только транспортный слой (HTTP-middleware, консьюмер
RabbitMQ, воркер TaskIQ). Бизнес-код контекст читает, но не пишет.
"""

from contextvars import ContextVar
from uuid import UUID

#: Идентификатор запроса. Дефис вместо None, чтобы форматирование логов
#: никогда не спотыкалось о пустое значение вне запроса (миграции, скрипты).
request_id: ContextVar[str] = ContextVar("request_id", default="-")

#: Пользователь, от имени которого выполняется операция. None — системный вызов.
actor_id: ContextVar[UUID | None] = ContextVar("actor_id", default=None)
