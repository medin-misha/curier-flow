type MessageShape<T> = T extends (...args: infer Args) => string
  ? (...args: Args) => string
  : T extends string
    ? string
    : T extends readonly unknown[]
      ? { readonly [Key in keyof T]: MessageShape<T[Key]> }
      : { readonly [Key in keyof T]: MessageShape<T[Key]> }

